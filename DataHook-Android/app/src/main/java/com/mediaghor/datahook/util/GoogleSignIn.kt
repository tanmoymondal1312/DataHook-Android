package com.mediaghor.datahook.util

import android.app.Activity
import android.content.Context
import android.content.ContextWrapper
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.mediaghor.datahook.R

/** The user dismissed the Google account chooser — not an error worth showing. */
class GoogleSignInCancelled : Exception("Sign-in cancelled")

/**
 * Shows the Google account chooser and returns the resulting ID token.
 *
 * The token's audience is the project's **Web** client ID
 * (`R.string.default_web_client_id`, generated by the google-services plugin
 * from `google-services.json`), which is what `/api/auth/google/` verifies
 * against. Nothing is persisted here — the backend owns the session.
 */
suspend fun requestGoogleIdToken(context: Context): Result<String> = runCatching {
    val option = GetSignInWithGoogleOption
        .Builder(context.getString(R.string.default_web_client_id))
        .build()

    val request = GetCredentialRequest.Builder()
        .addCredentialOption(option)
        .build()

    // The chooser is a UI flow, so it must be anchored to the Activity.
    val activity = context.findActivity()
        ?: error("Google sign-in must be started from an Activity")

    val credential = CredentialManager.create(context)
        .getCredential(activity, request)
        .credential

    val isGoogleToken = credential is CustomCredential &&
        credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
    if (!isGoogleToken) error("Unexpected credential type: ${credential.type}")

    GoogleIdTokenCredential.createFrom(credential.data).idToken
}.recoverCatching { throwable ->
    if (throwable is GetCredentialCancellationException) throw GoogleSignInCancelled()
    throw throwable
}

private fun Context.findActivity(): Activity? {
    var current = this
    while (current is ContextWrapper) {
        if (current is Activity) return current
        current = current.baseContext
    }
    return null
}
